"""Minimal, transparent migration runner for the `ai` schema.

    python -m app.migrate          apply pending migrations to AI_DATABASE_URL
    python -m app.migrate --status list applied and pending migrations
    python -m app.migrate --sql    print pending SQL (to paste into the Supabase SQL Editor)

Why not Alembic: the AI service uses plain asyncpg (no ORM). These migrations are
ordered SQL files tracked in ai.schema_migrations. Each one runs in its own
transaction, and a checksum detects a migration file that was edited after it was applied.
"""

import argparse
import asyncio
import hashlib
from dataclasses import dataclass
from pathlib import Path

import asyncpg

from .config import SERVICE_DIR, get_settings

MIGRATIONS_DIR = SERVICE_DIR / "db" / "migrations"

TRACKING_TABLE_SQL = """
CREATE TABLE IF NOT EXISTS ai.schema_migrations (
    version    text        PRIMARY KEY,
    checksum   text        NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT now()
)
"""


class MigrationError(Exception):
    pass


@dataclass(frozen=True)
class Migration:
    version: str  # file name without .sql, e.g. "0001_knowledge_base"
    sql: str

    @property
    def checksum(self) -> str:
        return hashlib.sha256(self.sql.encode("utf-8")).hexdigest()


def load_migrations(directory: Path = MIGRATIONS_DIR) -> list[Migration]:
    files = sorted(directory.glob("*.sql"))
    return [Migration(f.stem, f.read_text(encoding="utf-8")) for f in files]


async def _check_prerequisites(conn: asyncpg.Connection) -> None:
    if not await conn.fetchval("SELECT 1 FROM pg_extension WHERE extname = 'vector'"):
        raise MigrationError(
            "The 'vector' extension is not installed. Enable pgvector first "
            "(locally it is created by db/init; on Supabase enable it under Database > Extensions)."
        )
    # Only create the schema when it is missing: PostgreSQL checks the CREATE-on-database
    # permission even for "IF NOT EXISTS", and on Supabase the service's restricted login
    # owns an existing "ai" schema but may not create schemas (found in the step 6 deploy
    # rehearsal, Nov 27).
    if not await conn.fetchval("SELECT 1 FROM pg_namespace WHERE nspname = 'ai'"):
        await conn.execute("CREATE SCHEMA ai")
    await conn.execute(TRACKING_TABLE_SQL)


async def pending_migrations(conn: asyncpg.Connection, migrations: list[Migration]) -> list[Migration]:
    rows = await conn.fetch("SELECT version, checksum FROM ai.schema_migrations")
    applied = {r["version"]: r["checksum"] for r in rows}
    for m in migrations:
        if m.version in applied and applied[m.version] != m.checksum:
            raise MigrationError(
                f"Migration {m.version} was changed after it was applied. "
                "Never edit an applied migration; add a new one instead."
            )
    return [m for m in migrations if m.version not in applied]


async def apply_migrations(conn: asyncpg.Connection, migrations: list[Migration] | None = None) -> list[str]:
    """Apply pending migrations in order. Returns the versions applied."""
    migrations = load_migrations() if migrations is None else migrations
    await _check_prerequisites(conn)
    applied = []
    for m in await pending_migrations(conn, migrations):
        async with conn.transaction():
            await conn.execute(m.sql)
            await conn.execute(
                "INSERT INTO ai.schema_migrations (version, checksum) VALUES ($1, $2)",
                m.version, m.checksum,
            )
        applied.append(m.version)
    return applied


def render_sql(migrations: list[Migration]) -> str:
    """SQL for manual application (Supabase SQL Editor), including the tracking rows."""
    parts = ["-- Generated by python -m app.migrate --sql", "BEGIN;", "CREATE SCHEMA IF NOT EXISTS ai;",
             TRACKING_TABLE_SQL.strip() + ";"]
    for m in migrations:
        parts += [f"\n-- ==== {m.version} ====", m.sql.strip(),
                  f"INSERT INTO ai.schema_migrations (version, checksum) VALUES ('{m.version}', '{m.checksum}');"]
    parts.append("COMMIT;")
    return "\n".join(parts) + "\n"


async def _main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--status", action="store_true")
    group.add_argument("--sql", action="store_true")
    args = parser.parse_args()

    settings = get_settings()
    if settings.database_url is None:
        raise SystemExit("AI_DATABASE_URL is not set")
    conn = await asyncpg.connect(settings.database_url.get_secret_value(), timeout=settings.db_timeout_seconds)
    try:
        migrations = load_migrations()
        if args.sql or args.status:
            await _check_prerequisites(conn)
            pending = await pending_migrations(conn, migrations)
            if args.sql:
                print(render_sql(pending) if pending else "-- Nothing pending")
            else:
                for m in migrations:
                    print(f"{'pending ' if m in pending else 'applied '} {m.version}")
            return
        done = await apply_migrations(conn, migrations)
        print("Applied: " + ", ".join(done) if done else "Database is up to date")
    finally:
        await conn.close()


if __name__ == "__main__":
    asyncio.run(_main())
